"""
Session Blackboard - Skills-based Query History Navigation

This module provides session-level blackboard storage for the ReAct agent.
It stores ALL query results (successful AND failed) with skill descriptions,
enabling intelligent navigation through past queries.

Key Features:
- Session-scoped blackboard (persists across questions within same session)
- Full-text search with tsvector
- Fuzzy search with pg_trgm (OR queries supported)
- Skill descriptions generated by async Skill Agent
- Pagination for large result sets
- Session overview with preview

Usage:
    from src.shared.session_blackboard import (
        store_step,
        get_session_overview,
        search_skills,
        get_step_detail,
        get_step_results,
    )

Environment Variables:
    SESSION_BLACKBOARD_ENABLED: Enable/disable feature (default: true)
    SESSION_BLACKBOARD_TTL_HOURS: Hours to keep data (default: 24)
"""

