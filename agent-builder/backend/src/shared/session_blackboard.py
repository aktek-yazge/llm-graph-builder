@dataclass
class BlackboardStep:
    """A single step in the blackboard"""

    id: int
    session_id: str
    question_id: str
    question_text: str
    question_number: int
    step_number: int
    step_name: str
    skill_description: Optional[str] = None
    skill_tags: List[str] = field(default_factory=list)
    intent: Optional[str] = None
    cypher_query: str = ""
    query_type: str = "cypher"
    status: str = "success"
    record_count: int = 0
    result_preview: List[Dict] = field(default_factory=list)
    full_results: List[Dict] = field(default_factory=list)
    execution_time_ms: Optional[int] = None
    created_at: Optional[datetime] = None


@dataclass
class QuestionSummary:
    """Summary of a question with its steps"""

    question_id: str
    question_text: str
    question_number: int
    steps: List[BlackboardStep] = field(default_factory=list)
    total_steps: int = 0
    successful_steps: int = 0
    failed_steps: int = 0


